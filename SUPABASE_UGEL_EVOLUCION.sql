-- Impide que una cuenta acumule cientos de paquetes por error desde el cliente.
create or replace function public.limitar_paquetes_uniprep()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  if (select count(*) from public.ai_study_packs where user_id = new.user_id) >= 24
     and not exists (select 1 from public.ai_study_packs where user_id = new.user_id and id = new.id) then
    raise exception 'Límite de 24 materiales IA por estudiante';
  end if;
  new.updated_at := now();
  return new;
end;
$$;

drop trigger if exists limitar_paquetes_uniprep_trigger on public.ai_study_packs;
create trigger limitar_paquetes_uniprep_trigger
before insert or update on public.ai_study_packs
for each row execute function public.limitar_paquetes_uniprep();

revoke all on public.user_preferences, public.ai_study_packs, public.vocational_results, public.ai_feedback, public.ai_usage_events from anon;
grant select, insert, update, delete on public.user_preferences, public.ai_study_packs, public.vocational_results to authenticated;
grant select, insert on public.ai_feedback, public.ai_usage_events to authenticated;
grant usage, select on sequence public.ai_feedback_id_seq to authenticated;
grant usage, select on sequence public.ai_usage_events_id_seq to authenticated;

notify pgrst, 'reload schema';
