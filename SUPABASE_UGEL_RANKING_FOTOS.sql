-- Recupera el departamento que ya estaba guardado en Auth metadata.
update public.profiles as p
set procedencia = coalesce(nullif(p.procedencia, ''), u.raw_user_meta_data ->> 'procedencia'),
    avatar_url = coalesce(nullif(p.avatar_url, ''), u.raw_user_meta_data ->> 'avatar_url')
from auth.users as u
where p.id = u.id;

create or replace function public.sincronizar_metadata_uniprep()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  update public.profiles
  set procedencia = coalesce(new.raw_user_meta_data ->> 'procedencia', procedencia),
      avatar_url = coalesce(new.raw_user_meta_data ->> 'avatar_url', avatar_url)
  where id = new.id;
  return new;
end;
$$;

drop trigger if exists sincronizar_metadata_uniprep_trigger on auth.users;
create trigger sincronizar_metadata_uniprep_trigger
after insert or update of raw_user_meta_data on auth.users
for each row execute function public.sincronizar_metadata_uniprep();

create table if not exists public.score_events (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  event_type text not null default 'practica',
  points integer not null default 0 check (points between 0 and 5000),
  correct_answers integer not null default 0 check (correct_answers between 0 and 500),
  wrong_answers integer not null default 0 check (wrong_answers between 0 and 500),
  blank_answers integer not null default 0 check (blank_answers between 0 and 500),
  total_answers integer not null default 0 check (total_answers between 0 and 500),
  exam_score numeric(12,3),
  exam_max numeric(12,3),
  exam_percent numeric(5,2) check (exam_percent between 0 and 100),
  exam_scale text not null default '',
  university_id text not null default 'general',
  created_at timestamptz not null default now(),
  constraint score_events_totals_ok check (correct_answers + wrong_answers + blank_answers <= total_answers)
);

alter table public.score_events add column if not exists exam_max numeric(12,3);
alter table public.score_events add column if not exists exam_percent numeric(5,2);

create index if not exists score_events_user_date_idx on public.score_events(user_id, created_at desc);
create index if not exists score_events_date_idx on public.score_events(created_at desc);

alter table public.score_events enable row level security;
