with check (auth.uid() = user_id);
drop policy if exists "score_events_select_own" on public.score_events;
create policy "score_events_select_own" on public.score_events for select to authenticated
using (auth.uid() = user_id);

-- El ranking devuelve solo nombre público abreviado en la interfaz y datos agregados.
create or replace function public.obtener_ranking_uniprep_v2(
  p_periodo text default 'semana',
  p_region text default null
)
returns table (
  id uuid,
  nombre text,
  carrera text,
  procedencia text,
  avatar_url text,
  puntos_periodo bigint,
  preguntas_periodo bigint,
  correctas_periodo bigint,
  precision_periodo numeric,
  mejor_simulacro numeric,
  escala_simulacro text
)
language sql
stable
security definer
set search_path = public
as $$
  with parametros as (
    select case lower(coalesce(p_periodo, 'semana'))
      when 'dia' then date_trunc('day', now() at time zone 'America/Lima') at time zone 'America/Lima'
      when 'semana' then date_trunc('week', now() at time zone 'America/Lima') at time zone 'America/Lima'
      when 'mes' then date_trunc('month', now() at time zone 'America/Lima') at time zone 'America/Lima'
      else to_timestamp(0)
    end as desde
  ), eventos as (
    select e.user_id,
      sum(e.points)::bigint as puntos,
      sum(e.total_answers)::bigint as preguntas,
      sum(e.correct_answers)::bigint as correctas,
      max(e.exam_percent) as mejor,
      (array_agg(
        concat(
          trim(to_char(e.exam_score, 'FM999999990.000')),
          case when e.exam_max is not null then concat(' de ', trim(to_char(e.exam_max, 'FM999999990.000'))) else '' end,
          case when nullif(e.exam_scale, '') is not null then concat(' · ', e.exam_scale) else '' end
        ) order by e.exam_percent desc nulls last
      ) filter (where e.exam_score is not null and e.exam_percent is not null))[1] as escala
    from public.score_events e, parametros x
    where e.created_at >= x.desde
    group by e.user_id
  )
  select p.id,
    coalesce(nullif(p.nombre, ''), 'Estudiante UniPrep')::text,
    coalesce(nullif(p.carrera, ''), 'Preuniversitario')::text,
    coalesce(nullif(p.procedencia, ''), 'Sin región')::text,
    coalesce(p.avatar_url, '')::text,
    (case when lower(coalesce(p_periodo, 'semana')) = 'total'
      then greatest(coalesce(e.puntos, 0), coalesce(p.xp, 0)::bigint)
      else coalesce(e.puntos, 0) end)::bigint,
    (case when lower(coalesce(p_periodo, 'semana')) = 'total'
      then greatest(coalesce(e.preguntas, 0), coalesce(p.respuestas_totales, 0)::bigint)
      else coalesce(e.preguntas, 0) end)::bigint,
    (case when lower(coalesce(p_periodo, 'semana')) = 'total'
      then greatest(coalesce(e.correctas, 0), coalesce(p.respuestas_correctas, 0)::bigint)
      else coalesce(e.correctas, 0) end)::bigint,
    (case
      when lower(coalesce(p_periodo, 'semana')) = 'total' and coalesce(p.respuestas_totales, 0) > 0
        then round((p.respuestas_correctas::numeric / p.respuestas_totales::numeric) * 100, 1)
      when coalesce(e.preguntas, 0) > 0
        then round((e.correctas::numeric / e.preguntas::numeric) * 100, 1)
      else 0 end)::numeric,
    coalesce(e.mejor, 0)::numeric,
    coalesce(e.escala, '')::text
  from public.profiles p
  left join eventos e on e.user_id = p.id
  where coalesce(p.ranking_visible, true)
    and (p_region is null or lower(coalesce(p.procedencia, '')) = lower(p_region))
  order by 6 desc, 8 desc, 2 asc
  limit 500;
$$;

revoke all on function public.obtener_ranking_uniprep_v2(text, text) from public;
grant execute on function public.obtener_ranking_uniprep_v2(text, text) to authenticated;

