-- Crea y mantiene el perfil a partir de Auth sin guardar contraseñas.
create or replace function public.sincronizar_usuario_uniprep()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  metadata jsonb := coalesce(new.raw_user_meta_data, '{}'::jsonb);
begin
  insert into public.profiles (
    id, nombre, correo, carrera, universidad, procedencia, avatar_url
  ) values (
    new.id,
    coalesce(nullif(metadata ->> 'nombre', ''), nullif(split_part(coalesce(new.email, ''), '@', 1), ''), 'Estudiante UniPrep'),
    coalesce(new.email, ''),
    coalesce(metadata ->> 'carrera', ''),
    coalesce(metadata ->> 'universidad', ''),
    coalesce(metadata ->> 'procedencia', ''),
    coalesce(metadata ->> 'avatar_url', '')
  )
  on conflict (id) do update set
    correo = excluded.correo,
    nombre = coalesce(nullif(excluded.nombre, ''), public.profiles.nombre),
    carrera = coalesce(nullif(excluded.carrera, ''), public.profiles.carrera),
    universidad = coalesce(nullif(excluded.universidad, ''), public.profiles.universidad),
    procedencia = coalesce(nullif(excluded.procedencia, ''), public.profiles.procedencia),
    avatar_url = coalesce(nullif(excluded.avatar_url, ''), public.profiles.avatar_url),
    actualizado_en = now();
  return new;
end;
$$;

drop trigger if exists sincronizar_metadata_uniprep_trigger on auth.users;
drop trigger if exists sincronizar_usuario_uniprep_trigger on auth.users;
create trigger sincronizar_usuario_uniprep_trigger
after insert or update of email, raw_user_meta_data on auth.users
for each row execute function public.sincronizar_usuario_uniprep();

