revoke all on public.profiles, public.course_progress, public.activities, public.agenda_events,
  public.score_events, public.user_preferences, public.ai_study_packs, public.vocational_results,
  public.ai_feedback, public.ai_usage_events, public.universe_profiles, public.universe_events from anon;

grant select, insert, update on public.profiles to authenticated;
grant select, insert, update, delete on public.course_progress, public.activities, public.agenda_events,
  public.user_preferences, public.ai_study_packs, public.vocational_results, public.universe_profiles to authenticated;
grant select, insert on public.score_events, public.ai_feedback, public.ai_usage_events, public.universe_events to authenticated;

revoke all on function public.obtener_ranking_uniprep_v2(text, text) from public;
grant execute on function public.obtener_ranking_uniprep_v2(text, text) to authenticated;
revoke all on function public.eliminar_mi_cuenta_uniprep() from public;
grant execute on function public.eliminar_mi_cuenta_uniprep() to authenticated;

do $$
declare
  seq_name text;
begin
  foreach seq_name in array array[
    'activities_id_seq','agenda_events_id_seq','score_events_id_seq',
    'ai_feedback_id_seq','ai_usage_events_id_seq','universe_events_id_seq'
  ] loop
    if to_regclass('public.' || seq_name) is not null then
      execute format('grant usage, select on sequence public.%I to authenticated', seq_name);
    end if;
  end loop;
end;
$$;

notify pgrst, 'reload schema';

